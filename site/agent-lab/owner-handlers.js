// Thin owner binding for the adapter Graft will generate from index.html.
// It declares no WebMCP descriptor and never registers a tool directly.

import { registerGraftTools } from "./graft-adapter.js";
import { applyApprovedPatch, requestPatchConfirmation } from "./app.js";

const textResult = (text, structuredContent, isError = false) => ({
  content: [{ type: "text", text }],
  structuredContent,
  ...(isError ? { isError: true } : {}),
});

const isExactApplyPatchInput = (args) =>
  args !== null &&
  typeof args === "object" &&
  !Array.isArray(args) &&
  Object.keys(args).length === 1 &&
  typeof args.target === "string";

export async function registerAgentLabTools() {
  return registerGraftTools({
    confirm: ({ args, signal }) => requestPatchConfirmation({
      target: args.target,
      source: "agent",
      signal,
    }),
    handlers: {
      apply_patch: async (args = {}, context = {}) => {
        try {
          if (!isExactApplyPatchInput(args)) {
            return textResult(
              "apply_patch requires exactly one string field named target.",
              { approved: false, reason: "invalid_arguments" },
              true,
            );
          }
          const result = await applyApprovedPatch({
            target: args.target,
            signal: context.signal,
          });
          return textResult(
            `${result.patchId} applied after visible in-page approval. ${result.tests.passed} of ${result.tests.total} deterministic checks passed.`,
            result,
          );
        } catch (error) {
          const message = error instanceof Error ? error.message : String(error);
          return textResult(message, { approved: false, reason: message }, true);
        }
      },
    },
  });
}

const webmcpState = document.getElementById("webmcp-state");
const toolSurfaceState = document.getElementById("tool-surface-state");
const toolSurfaceTitle = document.getElementById("tool-surface-title");
const toolRegistrations = document.querySelectorAll("[data-tool-registration]");
const EXPECTED_TOOLS = [
  "get_page_summary",
  "get_page_outline",
  "list_files",
  "get_file",
  "list_patches",
  "get_patch",
  "list_test_results",
  "apply_patch",
];

void registerAgentLabTools()
  .then((report) => {
    const ready =
      report.failures.length === 0 &&
      report.missingHandlers.length === 0 &&
      report.registered.length === EXPECTED_TOOLS.length &&
      EXPECTED_TOOLS.every((name, index) => report.registered[index] === name);
    webmcpState.textContent = ready
      ? `${report.registered.length} tools live via Graft`
      : "WebMCP registration incomplete";
    toolSurfaceState.textContent = ready ? "live via Graft" : "registration incomplete";
    toolSurfaceTitle.textContent = ready
      ? "Eight exact tools, live via Graft."
      : "Eight reviewed tools generated by Graft.";
    document.documentElement.dataset.webmcp = ready ? "ready" : "incomplete";
    toolRegistrations.forEach((item) => {
      item.dataset.registrationState = ready ? "live" : "unavailable";
    });
    webmcpState.title = ready
      ? "Eight reviewed contracts generated by Graft are registered in this document."
      : "One or more reviewed contracts could not register.";
  })
  .catch((error) => {
    webmcpState.textContent = "WebMCP browser required";
    toolSurfaceState.textContent = "WebMCP browser required";
    toolSurfaceTitle.textContent = "Eight reviewed tools generated by Graft.";
    document.documentElement.dataset.webmcp = "unsupported";
    toolRegistrations.forEach((item) => {
      item.dataset.registrationState = "unsupported";
    });
    webmcpState.title = error instanceof Error ? error.message : String(error);
  });
